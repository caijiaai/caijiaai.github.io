SPEED = 3.7      # 字/秒（含标点计数，偏宽松，给后贴旁白留余量）
GAP_IN = 0.7    # 块间停顿
LEAD = {0: 0.9, 1: 1.4, 2: 1.4, 3: 1.2, 4: 1.4, 5: 1.4, 6: 1.4, 7: 1.4}  # 每段画面先行时间
TAIL = 1.6       # 段尾留白
END_CARD = 9.0   # 片尾卡：从最后一块开始起算


def build():
    """返回 segments: [{start,end,chunks:[{start,end,text,lines:[(t0,t1,text)]}]}], total"""
    for i, (txt, ch) in enumerate(zip(LOCKED, CHUNKS)):
        joined = "".join("".join(c) for c in ch)
        assert joined == txt, (i, joined, txt)
        for c in ch:
            assert len("".join(c)) <= 40, c
    t = 0.0
    segs = []
    for i, ch in enumerate(CHUNKS):
        s0 = t
        t += LEAD[i]
        chunks = []
        for j, c in enumerate(ch):
            text = "".join(c)
            dur = round(len(text) / SPEED, 2)
            c0 = round(t, 2); c1 = round(t + dur, 2)
            # 字幕：按两行一组显示，组内时长按字数分配
            groups = [c[k:k+2] for k in range(0, len(c), 2)]
            # 若 3 行，分为 [2,1] 或 [1,2]，取更均衡
            if len(c) == 3:
                a = [c[:2], c[2:]]; b = [c[:1], c[1:]]
                score = lambda g: abs(len("".join(g[0])) - len("".join(g[1])))
                groups = a if score(a) <= score(b) else b
            lines = []
            tt = c0
            for g in groups:
                gd = dur * len("".join(g)) / len(text)
                lines.append((round(tt, 2), round(tt + gd, 2), g))
                tt += gd
            chunks.append(dict(start=c0, end=c1, text=text, groups=lines))
            t = c1 + GAP_IN
        t = t - GAP_IN + TAIL
        segs.append(dict(start=round(s0, 2), end=round(t, 2), chunks=chunks))
    last = segs[-1]['chunks'][-1]
    total = max(last['start'] - 0.4 + END_CARD, last['end'] + 1.0)
    segs[-1]['end'] = round(total, 2)
    segs[-1]['endcard'] = round(total - 8.5, 2)
    return segs, round(total, 2)


if __name__ == "__main__":
    segs, total = build()
    n = 0
    for i, s in enumerate(segs):
        print(f"seg{i+1} {s['start']:7.2f}-{s['end']:7.2f} ({s['end']-s['start']:.1f}s)")
        for c in s['chunks']:
            n += 1
            print(f"   {n:2d} {c['start']:7.2f}-{c['end']:7.2f} {len(c['text']):2d} {c['text']}")
            for g in c['groups']:
                for l in g[2]:
                    assert len(l) <= 17, l
    print("total", total)
